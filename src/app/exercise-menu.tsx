import { useEffect, useRef, useState, type Dispatch, type KeyboardEvent, type MouseEvent, type RefObject, type SetStateAction } from 'react';
import { MoreVertical, RotateCcw, Trash2, Copy, ChevronDown, ChevronRight, ClipboardCheck, FileJson2, HardDrive, Download, Upload, HelpCircle, SkipForward, BookOpen, NotebookPen, Cloud, Sun, Moon } from 'lucide-react';
import type { SessionMeta } from '../model';
import { Button } from '../shared/ui/button';
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuLabel, DropdownMenuSub, DropdownMenuSubContent, DropdownMenuSubTrigger, DropdownMenuTrigger } from '../shared/ui/dropdown-menu';
import { isServerStorageActive } from '../sync/browser-db';
import { applyThemePreference, readThemePreference, THEME_STORAGE_KEY, type ThemePreference, writeThemePreference } from '../shared/lib/ui-prefs';
import { BREAKPOINT_MEDIA } from '../shared/lib/breakpoints';

export type ExerciseMenuActions = {
 onCheckCopy: () => void; onExportTutor: () => void; onOpenDriveBank: () => void; onNewProblem: () => void; onToggleSkip: () => void; onLessons: () => void;
 onEditScales: () => void; onEndSession: () => void; onResetSession: () => void; onShortcuts: () => void; onCloudPreview: () => void; onResetAll: () => void;
 onStartFractions: () => void; onStartDiagnostic: () => void; onUseExample: () => void; onUseCurrentExpression: () => void;
 onCopySession: () => void; onDownloadBackup: () => void; onImportFile: () => void; onImportJson: () => void; onOpenSync: () => void;
};

/** The header's "Exercise menu" (notebook actions). `open` stays owned by the app shell because it also makes the workspace inert. */
export function ExerciseMenu({ open: menu, setOpen: setMenu, invokerRef: menuInvoker, skipped, session, syncPanelOpen, setup, backup, actions: a }: {
 open: boolean; setOpen: Dispatch<SetStateAction<boolean>>; invokerRef: RefObject<HTMLButtonElement | null>; skipped: boolean;
 session: SessionMeta | undefined; syncPanelOpen: boolean; setup: boolean; backup: boolean; actions: ExerciseMenuActions;
}) {
 const menuKeyboardActivation = useRef(false);
 const [menuMore, setMenuMore] = useState(false), [sessionDetailsOpen, setSessionDetailsOpen] = useState(false);
 const [compactMenu, setCompactMenu] = useState(() => typeof window !== 'undefined' && typeof window.matchMedia === 'function' && window.matchMedia(BREAKPOINT_MEDIA.compact).matches);
 const [theme, setTheme] = useState<ThemePreference>(() => readThemePreference());
 const [inlineMenuSubmenu, setInlineMenuSubmenu] = useState<'practice' | 'data' | null>(null);
 const inlineMenuHover = useRef<'practice' | 'data' | null>(null);
 useEffect(() => {
  if (typeof window.matchMedia !== 'function') return;
  const compactQuery = window.matchMedia(BREAKPOINT_MEDIA.compact);
  const updateCompactMenu = () => {
   setCompactMenu(compactQuery.matches);
   setInlineMenuSubmenu(null);
   inlineMenuHover.current = null;
  };
  updateCompactMenu();
  compactQuery.addEventListener('change', updateCompactMenu);
  return () => compactQuery.removeEventListener('change', updateCompactMenu);
 }, []);
 useEffect(() => {
  const syncTheme = (event: StorageEvent) => {
   if (event.key !== THEME_STORAGE_KEY) return;
   const next = event.newValue === 'light' ? 'light' : 'dark';
   setTheme(next);
   applyThemePreference(next);
  };
  window.addEventListener('storage', syncTheme);
  return () => window.removeEventListener('storage', syncTheme);
 }, []);
 function toggleTheme() {
  const next: ThemePreference = theme === 'dark' ? 'light' : 'dark';
  writeThemePreference(next);
  applyThemePreference(next);
  setTheme(next);
 }
 useEffect(() => {
  if (menu) return;
  // Menu actions also close the controlled root directly with setMenu(false);
  // reset disclosures here because Radix onOpenChange is not guaranteed for those closes.
  setMenuMore(false);
  setSessionDetailsOpen(false);
  setInlineMenuSubmenu(null);
  inlineMenuHover.current = null;
 }, [menu]);
 function rememberMenuKeyboardActivation(event: KeyboardEvent<HTMLButtonElement>) {
  if (event.key === 'Enter' || event.key === ' ') menuKeyboardActivation.current = true;
 }
 function toggleMenuFromClick(event: MouseEvent<HTMLButtonElement>) {
  // Radix already toggled on keydown; ignore the native click generated by that same activation.
  const keyboardClickHandledByRadix = event.detail === 0 && event.nativeEvent.isTrusted && menuKeyboardActivation.current;
  menuKeyboardActivation.current = false;
  if (keyboardClickHandledByRadix) return;
  // Keep pointer clicks and click-only assistive/test activations working.
  setMenu(value => !value);
 }
 const practiceMenuActions = <>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onStartFractions(); }}>Start Round 1 · 20 fraction questions</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onStartDiagnostic(); }}>Start 30-question diagnostic</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onUseExample(); }}>Use example</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onUseCurrentExpression(); }}>Use current expression as new problem</DropdownMenuItem>
 </>;
 const dataMenuActions = <>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onCopySession(); }}><Copy aria-hidden="true" /><span>Copy full session JSON<span className="small menu-description">All questions, answers, steps &amp; session data</span></span></DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onDownloadBackup(); }}><Download aria-hidden="true" />Download backup file</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onImportFile(); }}><Upload aria-hidden="true" />Import backup file</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onImportJson(); }}>Import session JSON</DropdownMenuItem>
  <DropdownMenuItem onSelect={() => { setMenu(false); a.onOpenSync(); }}><Cloud aria-hidden="true" />Cloud sync and migration</DropdownMenuItem>
 </>;
 return <DropdownMenu open={menu} onOpenChange={value => { setMenu(value); if (!value) { setMenuMore(false); setSessionDetailsOpen(false); } }}><DropdownMenuTrigger asChild><Button ref={menuInvoker} aria-label="Exercise menu" size="icon" onPointerDown={event => event.preventDefault()} onKeyDown={rememberMenuKeyboardActivation} onClick={toggleMenuFromClick}><MoreVertical aria-hidden="true" /></Button></DropdownMenuTrigger><DropdownMenuContent aria-label="Notebook actions" className="notebook-menu" onCloseAutoFocus={event => {
    if (syncPanelOpen || setup || backup) event.preventDefault();
    if (setup || backup) requestAnimationFrame(() =>
      document.getElementById(setup ? 'problem-input' : 'session-json')?.focus({ preventScroll: true }));
   }}>
   <DropdownMenuItem className="menu-primary-action" onSelect={a.onCheckCopy}><ClipboardCheck aria-hidden="true" />Check · Copy for Review</DropdownMenuItem>
   <DropdownMenuItem onSelect={a.onExportTutor}><FileJson2 aria-hidden="true" />Export for tutor (JSON)</DropdownMenuItem>
   <DropdownMenuItem onSelect={a.onOpenDriveBank}><HardDrive aria-hidden="true" />Google Drive · Question bank</DropdownMenuItem>
   <DropdownMenuItem onSelect={a.onNewProblem}><NotebookPen aria-hidden="true" />New Problem</DropdownMenuItem>
   <DropdownMenuItem onSelect={a.onToggleSkip}>{skipped ? <RotateCcw aria-hidden="true" /> : <SkipForward aria-hidden="true" />}{skipped ? 'Unskip question' : 'Skip question'}</DropdownMenuItem>
   <DropdownMenuItem onSelect={a.onLessons}><BookOpen aria-hidden="true" />Lessons</DropdownMenuItem>
   <DropdownMenuItem onSelect={toggleTheme}>{theme === 'dark' ? <Sun aria-hidden="true" /> : <Moon aria-hidden="true" />}Switch to {theme === 'dark' ? 'light' : 'dark'} theme</DropdownMenuItem>
   <DropdownMenuItem className="menu-disclosure" aria-expanded={menuMore} aria-controls={menuMore ? 'more-notebook-actions' : undefined} onSelect={event => { event.preventDefault(); setMenuMore(value => !value); }}><span>Show more</span><ChevronDown className={menuMore ? 'menu-chevron menu-chevron-open' : 'menu-chevron'} aria-hidden="true" /></DropdownMenuItem>
   {menuMore && <div id="more-notebook-actions" className="menu-more-content">
    <DropdownMenuLabel className="menu-section-heading">Session</DropdownMenuLabel>
    <DropdownMenuItem className="menu-disclosure" aria-expanded={sessionDetailsOpen} aria-controls={sessionDetailsOpen ? 'session-details-info' : undefined} onSelect={event => { event.preventDefault(); setSessionDetailsOpen(value => !value); }}><BookOpen aria-hidden="true" /><span>Session details</span><ChevronDown className={sessionDetailsOpen ? 'menu-chevron menu-chevron-open' : 'menu-chevron'} aria-hidden="true" /></DropdownMenuItem>
    {sessionDetailsOpen && <div id="session-details-info" role="group" aria-label="Session details" className="session-details-panel">
     <p className="menu-info-value"><span>Session ID</span><span dir="ltr">{session?.id ?? '—'}</span></p>
     <p className="menu-info-value"><span>Math anxiety</span><span>{session?.anxiety ?? 'Not set'}</span></p>
     <p className="menu-info-value"><span>Energy</span><span>{session?.energy ?? 'Not set'}</span></p>
     <DropdownMenuItem onSelect={a.onEditScales}>Change</DropdownMenuItem>
    </div>}
    <DropdownMenuItem onSelect={a.onEndSession}>End session (record end time)</DropdownMenuItem>
    <DropdownMenuItem className="menu-danger" onSelect={a.onResetSession}><RotateCcw aria-hidden="true" />Reset current session</DropdownMenuItem>

    {compactMenu ? <>
     <DropdownMenuItem className="menu-disclosure" aria-expanded={inlineMenuSubmenu === 'practice'} aria-controls={inlineMenuSubmenu === 'practice' ? 'mobile-practice-actions' : undefined}
      onPointerMove={event => { if (event.pointerType === 'mouse') { inlineMenuHover.current = 'practice'; setInlineMenuSubmenu('practice'); } else inlineMenuHover.current = null; }}
      onPointerLeave={event => {
       if (event.pointerType !== 'mouse') return;
       if (inlineMenuHover.current === 'practice') inlineMenuHover.current = null;
       // This inline disclosure is part of the same menu. Prevent Radix from
       // dropping focus to the menu root while scrolling into its child items.
       if (inlineMenuSubmenu === 'practice') event.preventDefault();
      }}
      onKeyDown={event => { if (event.key === 'ArrowRight') { event.preventDefault(); setInlineMenuSubmenu('practice'); } else if (event.key === 'ArrowLeft' && inlineMenuSubmenu === 'practice') { event.preventDefault(); inlineMenuHover.current = null; setInlineMenuSubmenu(null); } }}
      onSelect={event => { event.preventDefault(); if (inlineMenuHover.current === 'practice') { inlineMenuHover.current = null; setInlineMenuSubmenu('practice'); } else { inlineMenuHover.current = null; setInlineMenuSubmenu(value => value === 'practice' ? null : 'practice'); } }}>
      <span>Practice</span><ChevronDown className={inlineMenuSubmenu === 'practice' ? 'menu-chevron menu-chevron-open' : 'menu-chevron'} aria-hidden="true" />
     </DropdownMenuItem>
     {inlineMenuSubmenu === 'practice' && <div id="mobile-practice-actions" role="group" aria-label="Practice actions" className="dropdown-sub-content-inline">{practiceMenuActions}</div>}
     <DropdownMenuItem className="menu-disclosure" aria-expanded={inlineMenuSubmenu === 'data'} aria-controls={inlineMenuSubmenu === 'data' ? 'mobile-data-actions' : undefined}
      onPointerMove={event => { if (event.pointerType === 'mouse') { inlineMenuHover.current = 'data'; setInlineMenuSubmenu('data'); } else inlineMenuHover.current = null; }}
      onPointerLeave={event => {
       if (event.pointerType !== 'mouse') return;
       if (inlineMenuHover.current === 'data') inlineMenuHover.current = null;
       // Keep focus in an expanded inline group when the pointer leaves its trigger.
       if (inlineMenuSubmenu === 'data') event.preventDefault();
      }}
      onKeyDown={event => { if (event.key === 'ArrowRight') { event.preventDefault(); setInlineMenuSubmenu('data'); } else if (event.key === 'ArrowLeft' && inlineMenuSubmenu === 'data') { event.preventDefault(); inlineMenuHover.current = null; setInlineMenuSubmenu(null); } }}
      onSelect={event => { event.preventDefault(); if (inlineMenuHover.current === 'data') { inlineMenuHover.current = null; setInlineMenuSubmenu('data'); } else { inlineMenuHover.current = null; setInlineMenuSubmenu(value => value === 'data' ? null : 'data'); } }}>
      <span>Data</span><ChevronDown className={inlineMenuSubmenu === 'data' ? 'menu-chevron menu-chevron-open' : 'menu-chevron'} aria-hidden="true" />
     </DropdownMenuItem>
     {inlineMenuSubmenu === 'data' && <div id="mobile-data-actions" role="group" aria-label="Data actions" className="dropdown-sub-content-inline">{dataMenuActions}</div>}
    </> : <>
     <DropdownMenuSub>
      <DropdownMenuSubTrigger>Practice<ChevronRight aria-hidden="true" /></DropdownMenuSubTrigger>
      <DropdownMenuSubContent aria-label="Practice actions">{practiceMenuActions}</DropdownMenuSubContent>
     </DropdownMenuSub>
     <DropdownMenuSub>
      <DropdownMenuSubTrigger>Data<ChevronRight aria-hidden="true" /></DropdownMenuSubTrigger>
      <DropdownMenuSubContent aria-label="Data actions">{dataMenuActions}</DropdownMenuSubContent>
     </DropdownMenuSub>
    </>}

    <DropdownMenuLabel className="menu-section-heading">Help</DropdownMenuLabel>
    <DropdownMenuItem onSelect={a.onShortcuts}><HelpCircle aria-hidden="true" />Keyboard shortcuts</DropdownMenuItem>

    <DropdownMenuLabel className="menu-section-heading danger-heading">Danger zone</DropdownMenuLabel>
    {isServerStorageActive() ? <DropdownMenuItem className="menu-danger" onSelect={a.onCloudPreview}><Trash2 aria-hidden="true" /><span>Preview cloud reset impact<span className="small menu-description">Read-only verification; no data is deleted and the question bank is protected.</span></span></DropdownMenuItem> : <DropdownMenuItem className="menu-danger" onSelect={a.onResetAll}><Trash2 aria-hidden="true" />Reset all local storage</DropdownMenuItem>}
   </div>}
  </DropdownMenuContent></DropdownMenu>;
}
