import { ExerciseMenuMore } from './exercise-menu-more';
import {
  useEffect,
  useRef,
  useState,
  type Dispatch,
  type KeyboardEvent,
  type MouseEvent,
  type RefObject,
  type SetStateAction,
} from 'react';
import {
  MoreVertical,
  RotateCcw,
  ChevronDown,
  ClipboardCheck,
  FileJson2,
  HardDrive,
  SkipForward,
  BookOpen,
  NotebookPen,
  Sun,
  Moon,
} from 'lucide-react';
import type { SessionMeta } from '../model';
import { Button } from '../shared/ui/button';
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuTrigger } from '../shared/ui/dropdown-menu';
import {
  applyThemePreference,
  readThemePreference,
  THEME_STORAGE_KEY,
  type ThemePreference,
  writeThemePreference,
} from '../shared/lib/ui-prefs';
import { BREAKPOINT_MEDIA } from '../shared/lib/breakpoints';

export type ExerciseMenuActions = {
  onCheckCopy: () => void;
  onExportTutor: () => void;
  onOpenDriveBank: () => void;
  onNewProblem: () => void;
  onToggleSkip: () => void;
  onLessons: () => void;
  onEditScales: () => void;
  onEndSession: () => void;
  onResetSession: () => void;
  onShortcuts: () => void;
  onCloudPreview: () => void;
  onResetAll: () => void;
  onStartFractions: () => void;
  onStartDiagnostic: () => void;
  onUseExample: () => void;
  onUseCurrentExpression: () => void;
  onCopySession: () => void;
  onDownloadBackup: () => void;
  onImportFile: () => void;
  onImportJson: () => void;
  onOpenSync: () => void;
};

/** The header's "Exercise menu" (notebook actions). `open` stays owned by the app shell because it also makes the workspace inert. */
export function ExerciseMenu({
  open: menu,
  setOpen: setMenu,
  invokerRef: menuInvoker,
  skipped,
  session,
  syncPanelOpen,
  setup,
  backup,
  actions: a,
}: {
  open: boolean;
  setOpen: Dispatch<SetStateAction<boolean>>;
  invokerRef: RefObject<HTMLButtonElement | null>;
  skipped: boolean;
  session: SessionMeta | undefined;
  syncPanelOpen: boolean;
  setup: boolean;
  backup: boolean;
  actions: ExerciseMenuActions;
}) {
  const menuKeyboardActivation = useRef(false);
  const [menuMore, setMenuMore] = useState(false),
    [sessionDetailsOpen, setSessionDetailsOpen] = useState(false);
  const [compactMenu, setCompactMenu] = useState(
    () => typeof window !== 'undefined' && typeof window.matchMedia === 'function' && window.matchMedia(BREAKPOINT_MEDIA.compact).matches,
  );
  const [theme, setTheme] = useState<ThemePreference>(() => readThemePreference());
  const [inlineMenuSubmenu, setInlineMenuSubmenu] = useState<'practice' | 'data' | null>(null);
  const inlineMenuHover = useRef<'practice' | 'data' | null>(null);
  useEffect(() => {
    if (typeof window.matchMedia !== 'function') return;
    const compactQuery = window.matchMedia(BREAKPOINT_MEDIA.compact);
    const updateCompactMenu = () => {
      setCompactMenu(compactQuery.matches);
      setInlineMenuSubmenu(null);
      inlineMenuHover.current = null;
    };
    updateCompactMenu();
    compactQuery.addEventListener('change', updateCompactMenu);
    return () => compactQuery.removeEventListener('change', updateCompactMenu);
  }, []);
  useEffect(() => {
    const syncTheme = (event: StorageEvent) => {
      if (event.key !== THEME_STORAGE_KEY) return;
      const next = event.newValue === 'light' ? 'light' : 'dark';
      setTheme(next);
      applyThemePreference(next);
    };
    window.addEventListener('storage', syncTheme);
    return () => window.removeEventListener('storage', syncTheme);
  }, []);
  function toggleTheme() {
    const next: ThemePreference = theme === 'dark' ? 'light' : 'dark';
    writeThemePreference(next);
    applyThemePreference(next);
    setTheme(next);
  }
  useEffect(() => {
    if (menu) return;
    // Menu actions also close the controlled root directly with setMenu(false);
    // reset disclosures here because Radix onOpenChange is not guaranteed for those closes.
    setMenuMore(false);
    setSessionDetailsOpen(false);
    setInlineMenuSubmenu(null);
    inlineMenuHover.current = null;
  }, [menu]);
  function rememberMenuKeyboardActivation(event: KeyboardEvent<HTMLButtonElement>) {
    if (event.key === 'Enter' || event.key === ' ') menuKeyboardActivation.current = true;
  }
  function toggleMenuFromClick(event: MouseEvent<HTMLButtonElement>) {
    // Radix already toggled on keydown; ignore the native click generated by that same activation.
    const keyboardClickHandledByRadix = event.detail === 0 && event.nativeEvent.isTrusted && menuKeyboardActivation.current;
    menuKeyboardActivation.current = false;
    if (keyboardClickHandledByRadix) return;
    // Keep pointer clicks and click-only assistive/test activations working.
    setMenu((value) => !value);
  }
  return (
    <DropdownMenu
      open={menu}
      onOpenChange={(value) => {
        setMenu(value);
        if (!value) {
          setMenuMore(false);
          setSessionDetailsOpen(false);
        }
      }}
    >
      <DropdownMenuTrigger asChild>
        <Button
          ref={menuInvoker}
          aria-label="Exercise menu"
          size="icon"
          onPointerDown={(event) => event.preventDefault()}
          onKeyDown={rememberMenuKeyboardActivation}
          onClick={toggleMenuFromClick}
        >
          <MoreVertical aria-hidden="true" />
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent
        aria-label="Notebook actions"
        className="notebook-menu"
        onCloseAutoFocus={(event) => {
          if (syncPanelOpen || setup || backup) event.preventDefault();
          if (setup || backup)
            requestAnimationFrame(() => document.getElementById(setup ? 'problem-input' : 'session-json')?.focus({ preventScroll: true }));
        }}
      >
        <DropdownMenuItem className="menu-primary-action" onSelect={a.onCheckCopy}>
          <ClipboardCheck aria-hidden="true" />
          Check · Copy for Review
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={a.onExportTutor}>
          <FileJson2 aria-hidden="true" />
          Export for tutor (JSON)
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={a.onOpenDriveBank}>
          <HardDrive aria-hidden="true" />
          Google Drive · Question bank
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={a.onNewProblem}>
          <NotebookPen aria-hidden="true" />
          New Problem
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={a.onToggleSkip}>
          {skipped ? <RotateCcw aria-hidden="true" /> : <SkipForward aria-hidden="true" />}
          {skipped ? 'Unskip question' : 'Skip question'}
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={a.onLessons}>
          <BookOpen aria-hidden="true" />
          Lessons
        </DropdownMenuItem>
        <DropdownMenuItem onSelect={toggleTheme}>
          {theme === 'dark' ? <Sun aria-hidden="true" /> : <Moon aria-hidden="true" />}Switch to {theme === 'dark' ? 'light' : 'dark'} theme
        </DropdownMenuItem>
        <DropdownMenuItem
          className="menu-disclosure"
          aria-expanded={menuMore}
          aria-controls={menuMore ? 'more-notebook-actions' : undefined}
          onSelect={(event) => {
            event.preventDefault();
            setMenuMore((value) => !value);
          }}
        >
          <span>Show more</span>
          <ChevronDown className={menuMore ? 'menu-chevron menu-chevron-open' : 'menu-chevron'} aria-hidden="true" />
        </DropdownMenuItem>
        {menuMore && (
          <ExerciseMenuMore
            a={a}
            setMenu={setMenu}
            session={session}
            sessionDetailsOpen={sessionDetailsOpen}
            setSessionDetailsOpen={setSessionDetailsOpen}
            compactMenu={compactMenu}
            inlineMenuSubmenu={inlineMenuSubmenu}
            setInlineMenuSubmenu={setInlineMenuSubmenu}
            inlineMenuHover={inlineMenuHover}
          />
        )}
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
